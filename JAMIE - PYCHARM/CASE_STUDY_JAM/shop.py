def display_row(item_row):
    max_height = max(len(f["art"]) for f in item_row)

    for i in range(max_height):
        parts = []
        for item in item_row:
            if i < len(item["art"]):
                parts.append(item["art"][i])
            else:
                parts.append(" " * len(item["art"][0]))
        print("    ".join(parts))

    status_line = []
    for item in item_row:
        if item["unlocked"]:
            status_line.append(f"\t\t\t\t\t[UNLOCKED]")
        else:
            status_line.append(f"\t\t\t\t\t [LOCKED]")
    print("    ".join(status_line))

    press_line = []
    for item in item_row:
        press_line.append(f"\t\t\t\t\t[PRESS {item['id']}]")
    print("    ".join(press_line))

    price_line = []
    for item in item_row:
        price_line.append(f"\t\t\t\t\tPrice: {item['price']}")
    print("    ".join(price_line))

    print("\n")

